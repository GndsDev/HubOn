CREATE TABLE cash_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    opened_by_user_id BIGINT NOT NULL,
    opened_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opening_balance NUMERIC(12, 2) NOT NULL DEFAULT 0,
    closed_by_user_id BIGINT,
    closed_at TIMESTAMP WITHOUT TIME ZONE,
    expected_cash NUMERIC(12, 2),
    counted_cash NUMERIC(12, 2),
    difference_amount NUMERIC(12, 2),
    closing_note VARCHAR(500),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cash_shifts_opened_by_user
        FOREIGN KEY (opened_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_shifts_closed_by_user
        FOREIGN KEY (closed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_cash_shifts_status
        CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT chk_cash_shifts_opening_balance
        CHECK (opening_balance >= 0),
    CONSTRAINT chk_cash_shifts_counted_cash
        CHECK (counted_cash IS NULL OR counted_cash >= 0),
    CONSTRAINT chk_cash_shifts_closing_note
        CHECK (closing_note IS NULL OR btrim(closing_note) <> ''),
    CONSTRAINT chk_cash_shifts_lifecycle
        CHECK (
            (
                status = 'OPEN'
                AND closed_by_user_id IS NULL
                AND closed_at IS NULL
                AND expected_cash IS NULL
                AND counted_cash IS NULL
                AND difference_amount IS NULL
            )
            OR
            (
                status = 'CLOSED'
                AND closed_by_user_id IS NOT NULL
                AND closed_at IS NOT NULL
                AND closed_at >= opened_at
                AND expected_cash IS NOT NULL
                AND counted_cash IS NOT NULL
                AND difference_amount = counted_cash - expected_cash
            )
        ),
    CONSTRAINT chk_cash_shifts_timestamps
        CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX uq_cash_shifts_single_open
    ON cash_shifts ((1))
    WHERE status = 'OPEN';

CREATE INDEX idx_cash_shifts_opened_at
    ON cash_shifts (opened_at DESC);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    restaurant_table_id BIGINT,
    table_number_snapshot INTEGER,
    customer_name VARCHAR(120),
    customer_phone VARCHAR(30),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    service_fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    opened_by_user_id BIGINT NOT NULL,
    opened_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_by_user_id BIGINT,
    closed_at TIMESTAMP WITHOUT TIME ZONE,
    closed_business_date DATE,
    cancelled_by_user_id BIGINT,
    cancelled_at TIMESTAMP WITHOUT TIME ZONE,
    cancellation_reason VARCHAR(500),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sales_restaurant_table
        FOREIGN KEY (restaurant_table_id)
        REFERENCES restaurant_tables(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_opened_by_user
        FOREIGN KEY (opened_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_closed_by_user
        FOREIGN KEY (closed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_cancelled_by_user
        FOREIGN KEY (cancelled_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_sales_type
        CHECK (type IN ('TABLE', 'COUNTER')),
    CONSTRAINT chk_sales_status
        CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT chk_sales_origin
        CHECK (
            (
                type = 'TABLE'
                AND restaurant_table_id IS NOT NULL
                AND table_number_snapshot IS NOT NULL
                AND table_number_snapshot > 0
            )
            OR
            (
                type = 'COUNTER'
                AND restaurant_table_id IS NULL
                AND table_number_snapshot IS NULL
            )
        ),
    CONSTRAINT chk_sales_customer_name
        CHECK (customer_name IS NULL OR btrim(customer_name) <> ''),
    CONSTRAINT chk_sales_customer_phone
        CHECK (customer_phone IS NULL OR btrim(customer_phone) <> ''),
    CONSTRAINT chk_sales_amounts
        CHECK (
            service_fee >= 0
            AND discount_amount >= 0
        ),
    CONSTRAINT chk_sales_lifecycle
        CHECK (
            (
                status = 'OPEN'
                AND closed_by_user_id IS NULL
                AND closed_at IS NULL
                AND closed_business_date IS NULL
                AND cancelled_by_user_id IS NULL
                AND cancelled_at IS NULL
                AND cancellation_reason IS NULL
            )
            OR
            (
                status = 'CLOSED'
                AND closed_by_user_id IS NOT NULL
                AND closed_at IS NOT NULL
                AND closed_at >= opened_at
                AND closed_business_date IS NOT NULL
                AND cancelled_by_user_id IS NULL
                AND cancelled_at IS NULL
                AND cancellation_reason IS NULL
            )
            OR
            (
                status = 'CANCELLED'
                AND closed_by_user_id IS NULL
                AND closed_at IS NULL
                AND closed_business_date IS NULL
                AND cancelled_by_user_id IS NOT NULL
                AND cancelled_at IS NOT NULL
                AND cancelled_at >= opened_at
                AND cancellation_reason IS NOT NULL
                AND btrim(cancellation_reason) <> ''
            )
        ),
    CONSTRAINT chk_sales_timestamps
        CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX uq_sales_one_open_per_table
    ON sales (restaurant_table_id)
    WHERE type = 'TABLE' AND status = 'OPEN';

CREATE INDEX idx_sales_open_operation
    ON sales (status, type, opened_at DESC);

CREATE INDEX idx_sales_table_history
    ON sales (restaurant_table_id, opened_at DESC, id DESC)
    WHERE restaurant_table_id IS NOT NULL;

CREATE INDEX idx_sales_closed_reports
    ON sales (status, closed_business_date, type, closed_at, id);

CREATE INDEX idx_sales_cancelled_at
    ON sales (cancelled_at)
