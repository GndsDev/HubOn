CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    delta_quantity NUMERIC(15, 3) NOT NULL,
    previous_balance NUMERIC(15, 3) NOT NULL,
    resulting_balance NUMERIC(15, 3) NOT NULL,
    sale_item_id BIGINT,
    reversed_movement_id BIGINT,
    reason VARCHAR(500),
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stock_movements_stock_item
        FOREIGN KEY (stock_item_id) REFERENCES stock_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movements_sale_item
        FOREIGN KEY (sale_item_id) REFERENCES sale_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movements_reversed_movement
        FOREIGN KEY (reversed_movement_id)
        REFERENCES stock_movements(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movements_created_by_user
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT uq_stock_movements_reversed_movement
        UNIQUE (reversed_movement_id),
    CONSTRAINT chk_stock_movements_type
        CHECK (type IN ('ENTRY', 'SALE', 'SALE_REVERSAL', 'EXIT', 'LOSS', 'ADJUSTMENT')),
    CONSTRAINT chk_stock_movements_delta_direction
        CHECK (
            (type IN ('ENTRY', 'SALE_REVERSAL') AND delta_quantity > 0)
            OR (type IN ('SALE', 'EXIT', 'LOSS') AND delta_quantity < 0)
            OR (type = 'ADJUSTMENT' AND delta_quantity <> 0)
        ),
    CONSTRAINT chk_stock_movements_balances
        CHECK (
            previous_balance >= 0
            AND resulting_balance >= 0
            AND resulting_balance = previous_balance + delta_quantity
        ),
    CONSTRAINT chk_stock_movements_origin
        CHECK (
            (
                type = 'SALE'
                AND sale_item_id IS NOT NULL
                AND reversed_movement_id IS NULL
            )
            OR
            (
                type = 'SALE_REVERSAL'
                AND sale_item_id IS NOT NULL
                AND reversed_movement_id IS NOT NULL
            )
            OR
            (
                type IN ('ENTRY', 'EXIT', 'LOSS', 'ADJUSTMENT')
                AND sale_item_id IS NULL
                AND reversed_movement_id IS NULL
            )
        ),
    CONSTRAINT chk_stock_movements_not_self_reversal
        CHECK (reversed_movement_id IS NULL OR reversed_movement_id <> id),
    CONSTRAINT chk_stock_movements_reason
        CHECK (
            (reason IS NULL OR btrim(reason) <> '')
            AND (
                type NOT IN ('LOSS', 'ADJUSTMENT')
                OR (reason IS NOT NULL AND btrim(reason) <> '')
            )
        )
);

