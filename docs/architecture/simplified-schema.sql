-- Cross-table invariants intentionally remain in transactional services:
-- 1. subtotal_amount is derived from the sum of active sale_items;
-- 2. item option selections respect each active group's minimum and maximum;
-- 3. item unit price equals base price plus selected option snapshots;
-- 4. final_amount is derived from subtotal, service_fee and discount_amount;
-- 5. paid_amount and remaining_amount are derived from SUM(payments.amount);
-- 6. SUM(payments.amount) never exceeds the derived final_amount;
-- 7. sale items cannot be altered or cancelled after the first payment;
-- 8. a sale with payments cannot be cancelled without a financial reversal flow;
-- 9. CLOSED sales have exact payment and at least one active item;
-- 10. zero-value COUNTER sales do not close automatically;
-- 11. stock movement reversal targets a SALE for the same item and stock item;
-- 12. operational payments use the currently OPEN cash shift;
-- 13. closed/cancelled sales and ledger records are immutable.
