CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name_snapshot VARCHAR(120) NOT NULL,
    -- The application stores 'Sem categoria' when products.category_id is NULL.
    category_name_snapshot VARCHAR(120) NOT NULL,
    base_unit_price_snapshot NUMERIC(12, 2) NOT NULL,
    unit_price_snapshot NUMERIC(12, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    notes VARCHAR(500),
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMP WITHOUT TIME ZONE,
    cancelled_by_user_id BIGINT,
    cancellation_reason VARCHAR(500),

    CONSTRAINT fk_sale_items_sale
        FOREIGN KEY (sale_id) REFERENCES sales(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_items_product
        FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_items_created_by_user
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_items_cancelled_by_user
        FOREIGN KEY (cancelled_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_sale_items_product_snapshot
        CHECK (btrim(product_name_snapshot) <> ''),
    CONSTRAINT chk_sale_items_category_snapshot
        CHECK (btrim(category_name_snapshot) <> ''),
    CONSTRAINT chk_sale_items_prices
        CHECK (
            base_unit_price_snapshot >= 0
            AND unit_price_snapshot >= base_unit_price_snapshot
            AND subtotal >= 0
        ),
    CONSTRAINT chk_sale_items_quantity
        CHECK (quantity > 0),
    CONSTRAINT chk_sale_items_subtotal
        CHECK (subtotal = unit_price_snapshot * quantity),
    CONSTRAINT chk_sale_items_notes
        CHECK (notes IS NULL OR btrim(notes) <> ''),
    CONSTRAINT chk_sale_items_cancellation
        CHECK (
            (
                cancelled_at IS NULL
                AND cancelled_by_user_id IS NULL
                AND cancellation_reason IS NULL
            )
            OR
            (
                cancelled_at IS NOT NULL
                AND cancelled_at >= created_at
                AND cancelled_by_user_id IS NOT NULL
                AND cancellation_reason IS NOT NULL
                AND btrim(cancellation_reason) <> ''
            )
        )
);

CREATE INDEX idx_sale_items_active_by_sale
